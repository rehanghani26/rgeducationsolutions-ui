/**
 * Resolves an authentic, high-quality product image URL from its name, subcategory or category.
 */
export const getSchoolProductImage = (product = {}) => {
  if (product?.imageUrl && typeof product.imageUrl === 'string' && product.imageUrl.trim()) {
    return product.imageUrl;
  }
  const text = `${product?.name || ''} ${product?.subcategory || ''} ${product?.description || ''}`.toLowerCase();
  for (const [key, url] of Object.entries(SPECIFIC_PRODUCT_IMAGES)) {
    if (text.includes(key)) {
      return url;
    }
  }
  return CATEGORY_FALLBACK_IMAGES[product?.category] || CATEGORY_FALLBACK_IMAGES.General;
};

